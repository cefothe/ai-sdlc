// Regression for the basket-templates order-ref design (premia_v3 PR #179):
// DEC-0548 chained five decisions with ";", gave no reason per ref segment, and AC-35
// packed a format, a position ref, tags and the no-duplicate guarantee into one line.
// The "before" artifacts are the originals; the "after" artifacts are the same
// content rewritten so every decision carries its reason.

const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const yaml = require('js-yaml');
const { evaluateAdrQuality } = require('../../../decision-engine/decisions');
const { identifierWalkthroughIssues, decisionReasonIssues } = require('../../../decision-engine/design-gate');
const { parsePrd, acceptanceCriterionIssues } = require('../../../decision-engine/prd-gate');

const FIXTURES = join(__dirname, '..', '..', 'fixtures', 'order-refs');
const load = (f) => yaml.load(readFileSync(join(FIXTURES, f), 'utf8'));
const read = (f) => readFileSync(join(FIXTURES, f), 'utf8');
const codes = (issues) => issues.map((i) => i.code);

describe('DEC-0548 as shipped', () => {
  const result = evaluateAdrQuality(load('DEC-0548.original.yaml'));

  test('is rejected for bundling five decisions into one option', () => {
    expect(result.valid).toBe(false);
    expect(result.issues.join(' ')).toMatch(/bundles \d+ decisions/);
  });

  test('is rejected for defining a ref format without a reason per part', () => {
    expect(result.issues.join(' ')).toMatch(/no "## Why each part" section/);
  });

  test('is rejected for a rejected option that gives no cost of its own', () => {
    const d = load('DEC-0548.original.yaml');
    d.spec.options[1].description = 'Rejected.';
    expect(evaluateAdrQuality(d).issues.join(' ')).toMatch(/rejected option "call-in-transaction" gives no reason/);
  });
});

describe('the rewritten decisions', () => {
  test.each(['DEC-0548.yaml', 'DEC-0554.yaml', 'DEC-0555.yaml'])('%s is complete and atomic', (file) => {
    const r = evaluateAdrQuality(load(file));
    expect(r.issues).toEqual([]);
    expect(r.valid).toBe(true);
  });

  test('the ref-format ADR explains each part and names its unverified assumption', () => {
    const d = load('DEC-0554.yaml');
    expect(evaluateAdrQuality(d).warnings).toEqual([]);
    delete d.spec.body;
    const r = evaluateAdrQuality(d);
    expect(r.valid).toBe(false);
    expect(r.issues.join(' ')).toMatch(/Why each part/);
    expect(r.warnings.join(' ')).toMatch(/Assumptions/);
  });
});

describe('the design around the order ref', () => {
  const sectionsOf = (file) => parsePrd(read(file)).sections;
  const markdownOf = (file) => read(file);

  test('before: no walkthrough and a Decisions line that states what but not why', () => {
    expect(codes(identifierWalkthroughIssues(sectionsOf('design-before.md'), markdownOf('design-before.md')))).toEqual(['identifier-walkthrough-missing']);
    expect(codes(decisionReasonIssues(sectionsOf('design-before.md')))).toEqual(['decision-no-reason']);
  });

  test('after: walkthrough names generator, timing, per-part reasons, crash scenarios and the unverified assumption', () => {
    expect(identifierWalkthroughIssues(sectionsOf('design-after.md'), markdownOf('design-after.md'))).toEqual([]);
    expect(decisionReasonIssues(sectionsOf('design-after.md'))).toEqual([]);
  });

  test('after: dropping any required part of the walkthrough is reported by its own code', () => {
    const md = read('design-after.md');
    const without = (pattern) => md.replace(pattern, '');
    const issuesFor = (text) => codes(identifierWalkthroughIssues(parsePrd(text).sections, text));
    expect(issuesFor(without(/- Generated by:.*\n/))).toEqual(['identifier-no-generator']);
    expect(issuesFor(without(/- Generated when:.*\n/))).toEqual(['identifier-no-timing']);
    expect(issuesFor(without(/- Verified:.*\n/))).toEqual(['identifier-no-verification']);
    expect(issuesFor(without(/\| Part \| Why \|[\s\S]*?\n\n/))).toEqual(['identifier-format-unexplained']);
    expect(issuesFor(without(/\| Scenario \|[\s\S]*?\n\n/))).toEqual(['identifier-no-scenarios']);
  });
});

describe('AC-35', () => {
  const original = 'Every basket order is sent through the trading caller API with `client_order_ref` `<basket_id>:<market_id>:<attempt>` (or the top-up form), `client_position_ref` = basket id and client tags; after a crash or retry no duplicate venue order exists.';
  const rewritten = [
    'After a worker crash or a retried send, the venue holds at most one order per basket leg. Why: a duplicate order is a duplicate real-money position.',
    'Every basket order can be traced in trading to its basket and end client. Why: operators reconcile exposure per basket.',
  ];

  test('as written: no Why, and a format plus three field names inside the criterion', () => {
    expect(codes(acceptanceCriterionIssues([original]))).toEqual(['ac-no-why', 'ac-implementation-detail']);
  });

  test('rewritten as two single-outcome criteria, each with its reason', () => {
    expect(acceptanceCriterionIssues(rewritten)).toEqual([]);
  });
});
